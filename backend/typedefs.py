def match_deriv(t):
    """细颗粒度归类:同一题型里的题,解题方法必须是同一套(不允许"如果…就…"分叉)。"""
    if re.search(r'曲率', t):
        return '曲率'
    if re.search(r'切线|法线|相切|公切', t):                 # 切线家族:按"曲线怎么给"+"要什么"再分
        if re.search(r'相切|公切', t):
            return '两曲线相切求参数'
        if re.search(r'求曲线|曲线方程|求.{0,4}表达式|满足.{0,8}方程|恒为|恒等于|之比恒', t):
            return '由切线几何条件反求曲线'
        if re.search(r'极坐标', t):
            return '极坐标曲线的切线'
        if re.search(RE_PARAM, t):
            return '参数方程曲线的切线与法线'
        return '隐式曲线的切线与法线'
    if re.search(RE_PARAM, t):
        return '参数方程求导'
    if re.search(RE_IMPLICIT, t):
        return '隐函数求导'
    if re.search(r'不可导|可导.{0,10}(充要|条件)|分段', t):
        return '分段函数的可导性'
    if re.search(r'n\s*阶', t):                            # n 阶通项 与 具体某阶值 是两套做法
        return '求 n 阶导数通项'
    if re.search(r'阶导数|二阶导|′′′|f′′|y′′|[fy]\(\d+\)\s*\(|[fy]\(n\)\s*\(', t):
        return '求具体高阶导数值'
    if re.search(r'(可导|导数|f′).{0,60}lim|lim.{0,60}(可导|f′)|导数定义', t):
        return '用定义/极限求导数值(抽象函数)'
    return ''


def _strip(h):
    return re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', h or '')).strip()


def level_of(qtype):
    return '基础' if qtype in ('choice', 'blank') else '综合'


def _match(patterns, text):
    for pat, name in patterns:
        if re.search(pat, text):
            return name
    return ''


def classify_by_point(point, stem, sol='', year=None, number=None):
    """真题:返回 (题型名, 归并后的具体点)。未归纳的点原样返回 ('', point)。
    定积分应用用 题干+解析 判断(面积/体积等常只出现在解析里);导数片只看题干(题干就写明了函数形式)。
    重积分的计算:逐题人工钉死(见 bucket_zjf),按 年#题号 查表。"""
    if point == DEMO_POINT:
        return (_match(DJF_PATTERNS, stem + ' ' + sol) or '定积分的应用·未拆分'), DEMO_POINT
    if point in DERIV_POINTS:
        return (match_deriv(stem) or '导数概念与杂项'), DERIV_GROUP
    if point == ZJF.POINT:
        if ZJF.is_misfiled(stem):          # 求面积/旋转体体积 → 其实是「定积分的应用」
            return (_match(DJF_PATTERNS, stem + ' ' + sol) or '定积分的应用·未拆分'), DEMO_POINT
        return ZJF.pick_real(year, number, stem), point
    return '', point


